package com.redmi.autoattend.exec

/**
 * 钉钉界面上所有用于定位的元素。
 *
 * ## 实测校准（Redmi K90 至尊版 / 1280x2772 / 钉钉当前版本）
 *
 * ### 消息页顶部快捷区（这是进入打卡页的**正确入口**）
 *
 * uiautomator dump 实测：
 *
 *     text="日历"  id=im_ding_kit_item_txt  clickable=false  bounds=[169,362][259,423]
 *     text="待办"  id=im_ding_kit_item_txt  clickable=false  bounds=[408,362][498,423]
 *     text="打卡"  id=im_ding_kit_item_txt  clickable=false  bounds=[784,362][874,423]
 *     text="通话"  id=im_ding_kit_item_txt  clickable=false  bounds=[1020,363][1079,422]
 *
 * 要点：**节点本身 clickable=false**，文本挂在内层 TextView 上，
 * 必须点它的可点击父节点（clickableAncestorOrSelf 已处理）。
 *
 * ### 真实考勤打卡页（真机截图逐字记录）
 *
 *     ┌─────────────┬──────────────────────────┐
 *     │ 上班09:30   │ 下班18:30                │
 *     │ ✓ 09:19已打卡│ ✓ 18:30已打卡  更新打卡  │
 *     └─────────────┴──────────────────────────┘
 *                ┌──────────────┐
 *                │    外勤      │
 *                │  下班打卡    │
 *                │ 11月11日 周三│
 *                │  20:38:37    │
 *                └──────────────┘
 *       ⌖ 未进入考勤范围，可外勤打卡
 *            如需内勤打卡，请检查
 *     ─────────────────────────────
 *        打卡        统计        设置
 *
 * ## 三条从这里读出来的硬事实（每一条都改变实现）
 *
 * **1. 状态卡的时间与「已打卡」之间没有空格**
 *     真实是 "09:19已打卡"，不是 "09:19 已打卡"。
 *     所以任何"按空格切词"的解析都不可靠，只能做子串匹配。
 *
 * **2. 「更新打卡」里也含「打卡」二字**
 *     一个已完成的班次，卡片上会同时出现"已打卡"和"更新打卡"。
 *     用 contains("打卡") 判断"有没有打"，100% 会误判 ——
 *     必须用精确的"已打卡"/"未打卡"。
 *
 * **3. 已打卡之后，大按钮依然存在且可点**
 *     状态卡显示"18:30已打卡"的同时，中间那颗大圆按钮仍然写着
 *     "下班打卡" 并且可以点（钉钉允许重复打卡/更新打卡）。
 *     这就是为什么**不能靠"有没有按钮"判断该不该打** ——
 *     必须以状态卡为准，已完成就必须直接返回，否则会打出重复记录。
 *
 * **4. 外勤形态**
 *     大按钮上方多一行"外勤"，下方出现
 *     "未进入考勤范围，可外勤打卡" / "如需内勤打卡，请检查"。
 *     此时点击会生成一条**外勤记录**（很多公司需要额外审批）。
 *
 * 约定：
 * - **精确匹配优先**，包含匹配只作为最后兜底；
 * - 每个候选按"精确度"排序，不按"猜测的知名度"排序；
 * - 点击后必须校验页面确实发生了变化。
 */
object DingTalkUi {

    /** 钉钉包名 */
    const val PACKAGE = "com.alibaba.android.rimet"

    // ==================== 导航 ====================

    /**
     * 底部导航：工作台。
     *
     * 只放精确名。"工作"绝不作为候选——它会命中消息列表里的
     * "工作通知"、"工作台"以外的任何含"工作"的条目。
     */
    val TAB_WORK = listOf("工作台")

    /**
     * 首页顶部的"打卡"快捷入口（注意节点本身不可点，需点父级）。
     */
    val QUICK_PUNCH = listOf("打卡")

    /**
     * 考勤入口候选（工作台页里的应用图标）。
     *
     * 顺序：精确名在前。
     */
    val ENTRY_ATTENDANCE = listOf(
        "考勤打卡",
        "智能考勤",
        "考勤",
    )

    // ==================== 打卡按钮 ====================

    /**
     * "上班打卡"按钮候选。
     *
     * 注意：绝不能把裸"打卡"放进来 —— 页面上可能有"打卡记录"、
     * "打卡详情"、"查看详情"等多个含"打卡"的元素。
     */
    val BTN_CLOCK_IN = listOf(
        "上班打卡",
        "上班 打卡",
        "上班",
    )

    /** "下班打卡"按钮候选 */
    val BTN_CLOCK_OUT = listOf(
        "下班打卡",
        "下班 打卡",
        "下班",
    )

    // ==================== 结果判定 ====================

    /**
     * 打卡成功信号 —— 成功判定的唯一依据。
     *
     * 实测钉钉打卡成功后会弹出卡片，主文案是"打卡成功"，
     * 并附带"查看详情"。**"查看详情"本身不是成功信号**，
     * 它只说明弹出了某个结果卡片。
     */
    /**
     * 打卡成功的真实文案（真机取证，逐字复制）。
     *
     * ## 这里曾经完全匹配不上（识别不出成功的第二个独立原因）
     *
     * 真机上钉钉成功后弹出的卡片，原文是：
     *
     *     打卡结果
     *     18:30 下班打卡·成功          <- 注意：中点 U+00B7，不是 ·以外的任何符号
     *     班次时间 / 11月11日 18:30下班
     *     打卡方式 / 蓝牙打卡
     *     打卡设备 / 广州丰程商贸有限公司_41137 (蓝牙打卡)
     *
     * 旧候选表里是 打卡成功 / 考勤成功 / 打卡完成 / 更新成功 ——
     * **四个全都匹配不到**，因为真实文案是「下班打卡·成功」：
     * 「打卡」和「成功」之间隔着中点，而且「下班」在前。
     *
     * ## 匹配置信度排序
     *
     * 1. 精确的「X班打卡·成功」——最强证据，带班次；
     * 2. 通用的「打卡·成功」——只要出现就说明这一次真的成功了；
     * 3. 旧的无中点写法保留，兼容其它钉钉版本/其它企业的自定义文案。
     *
     * 注意：这些字符串必须**精确**，不能放裸「成功」或裸「打卡」，
     * 否则页面上的「更新打卡」「打卡记录」会污染判定。
     */
    val SUCCESS_SIGNALS = listOf(
        // ---- 真机实测文案（中点 U+00B7）----
        "上班打卡·成功",
        "下班打卡·成功",
        "打卡·成功",
        // ---- 兼容写法（普通点/无分隔符/其它版本）----
        "上班打卡·已成功",
        "下班打卡·已成功",
        "打卡成功",
        "考勤成功",
        "打卡完成",
        "更新成功",
    )

    /**
     * 已打卡（目标时段不需要再打）。
     *
     * ## 「更新打卡」是陷阱（真机截图确认）
     *
     * 已完成的班次卡片长这样：
     *
     *     ✓ 18:30已打卡  更新打卡
     *
     * "更新打卡" 里含"打卡"二字，它**不是**完成标记，而是"允许再打一次"的入口。
     * 任何 contains("打卡") 的判断都会把它算成信号。
     * 所以这里只放精确的"已打卡"/"未打卡"级文案，绝不放裸"打卡"。
     */
    val ALREADY_DONE_SIGNALS = listOf(
        "今日已打卡",
        "已完成打卡",
        "已打卡",
    )

    /**
     * 明确表示"这个时段还没打"的信号。
     *
     * 真机上未完成时状态卡写的是「未打卡」。
     * 它与 ALREADY_DONE_SIGNALS 是互斥的，判定时先用它排除，
     * 避免"未打卡"里含"打卡"、又被 ALREADY_DONE 的"已打卡"误命中
     * （"未打卡" 不含 "已打卡"，但版本差异下要显式防一手）。
     */
    val NOT_DONE_SIGNALS = listOf(
        "未打卡",
        "尚未打卡",
    )

    /**
     * 明确的失败信号。
     *
     * 判定顺序上必须先查失败再查成功：如果同时出现"打卡成功"和
     * "不在打卡范围"（部分成功的边缘情况），宁可判失败让用户知情。
     */
    val FAILURE_SIGNALS = listOf(
        "打卡失败",
        "不在打卡范围",
        "请在公司范围内打卡",
        "考勤组未设置",
        "网络异常",
        "打卡异常",
        "定位失败",
        "请开启定位",
    )

    /**
     * 「外勤打卡」信号 —— 检测到就**绝不能点**。
     *
     * 实测（Redmi K90 / 1280x2772 / 钉钉当前版本）打卡页有三种形态：
     *
     * 1. **内勤可打**：大按钮是绿色圆，文字"下班打卡"，下方无提示。
     * 2. **外勤可打**：大按钮顶部多一行"外勤"，变成"外勤 / 下班打卡"，
     *    下方出现"未进入考勤范围，可外勤打卡 / 如需内勤打卡，请检查"。
     * 3. **已打卡**：上方状态卡显示"09:30已打卡"。
     *
     * 第 2 种状态下点了会生成一条**外勤打卡记录**：
     * - 位置被记为"外勤"，很多公司需要额外审批才认；
     * - 有些公司直接不认外勤，等于白打还可能被标记异常；
     * - 而且它是"已打卡"状态，之后想补内勤就得走补卡流程。
     *
     * 所以用户明确要求：**发现外勤就先不打，等到能正常打卡为止**。
     */
    val OUTDOOR_SIGNALS = listOf(
        "未进入考勤范围",
        "可外勤打卡",
        "如需内勤打卡",
        "外勤打卡",
    )

    /** 判断当前页面是否是"外勤可打"状态 */
    fun isOutdoor(blob: String): Boolean {
        if (blob.isEmpty()) return false
        // "外勤" 单独出现在按钮上也算（大按钮第一行就是"外勤"）
        return OUTDOOR_SIGNALS.any { blob.contains(it) }
    }

    /** 常见弹窗关闭按钮 */
    val POPUP_DISMISS = listOf(
        "我知道了",
        "知道了",
        "关闭",
        "以后再说",
        "暂不",
        "跳过",
    )

    /**
     * 触发"点了但没跳转"误判的元素。
     *
     * 这些文本出现过就说明我们在错的地方（比如消息列表、汇报页）。
     * 用于导航校验：如果点完之后界面上出现了这些词，说明点错了。
     */
    val WRONG_PAGE_MARKERS = listOf(
        "汇报工作",
        "日志",
        "审批",
        "请假",
    )

    /** 钉钉关键 resourceId 前缀（辅助定位） */
    const val ID_PREFIX = "com.alibaba.android.rimet:id/"

    // ==================== 判定函数 ====================

    /**
     * 是否命中成功信号。
     *
     * ## 中点归一化（真机踩到）
     *
     * 真实文案「下班打卡·成功」里的中点是 U+00B7 (MIDDLE DOT)。
     * 但不同 ROM / 输入法 / 钉钉版本可能渲染成 U+2022(U+2022 BULLET)、
     * U+2027、全角「·」甚至直接是普通句点。硬编码某一种符号会在换版本时失效。
     *
     * 所以这里把常见分隔符统一成 U+00B7 再匹配 —— 只做**符号**归一化，
     * 绝不动汉字，避免引入新的不匹配。
     */
    fun containsSuccess(text: String): String? {
        if (text.isEmpty()) return null
        val normalized = normalizeSeparators(text)
        SUCCESS_SIGNALS.firstOrNull { normalized.contains(normalizeSeparators(it)) }?.let { return it }
        return null
    }

    /** 把各种「中点/间隔号」归一成 U+00B7，其余字符原样保留 */
    internal fun normalizeSeparators(s: String): String {
        val sb = StringBuilder(s.length)
        for (ch in s) {
            when (ch) {
                '\u00B7', '\u2022', '\u2027', '\u30FB', '\uFF65', '\u22C5', '\u0387' -> sb.append('\u00B7')
                else -> sb.append(ch)
            }
        }
        return sb.toString()
    }

    /** 是否命中"已打卡" */
    fun containsAlreadyDone(text: String): String? =
        ALREADY_DONE_SIGNALS.firstOrNull { text.contains(it) }

    /** 是否命中失败信号 */
    fun containsFailure(text: String): String? =
        FAILURE_SIGNALS.firstOrNull { text.contains(it) }

    /** 是否在错误页面（导航校验用） */
    fun looksLikeWrongPage(text: String): Boolean =
        WRONG_PAGE_MARKERS.any { text.contains(it) }
}