package com.redmi.autoattend.exec

/**
 * 钉钉界面上所有用于定位的元素。
 *
 * ## 实测校准（Redmi K90 至尊版 / 1280x2772 / 钉钉当前版本）
 *
 * 通过 uiautomator dump 实际抓取的界面结构：
 *
 * 首页顶部快捷入口：日历 / 待办 / **打卡** / 通话
 * 底部导航：千问办公 / **消息** / **工作台** / **通讯录** / 更多
 *
 * 注意：
 * 1. **没有"工作" tab**，叫"工作台"；
 * 2. 顶部那个"打卡"是快捷入口，但节点 text 非 clickable，
 *    需要点它的可点击父节点；
 * 3. 消息列表里有大量以"工作"开头的条目（如"工作通知"），
 *    用"包含匹配"点"工作"会命中错误目标 —— 这正是一开始
 *    "点不到查看详情、反而点进汇报工作"的根因。
 *
 * 因此本文件的核心约定变了：
 * - **必须精确匹配优先**，包含匹配只作为最后兜底；
 * - 每个候选按"精确度"排序，不按"猜测的知名度"排序；
 * - 点击后必须校验页面确实发生了变化。
 */
object DingTalkUi {

    /** 钉钉包名 */
    const val PACKAGE = "com.alibaba.android.rimet"

    // ==================== 导航 ====================

    /**
     * 底部导航：工作台。
     *
     * 只放精确名。"工作"绝不作为候选——它会命中消息列表里的
     * "工作通知"、"工作台"以外的任何含"工作"的条目。
     */
    val TAB_WORK = listOf("工作台")

    /**
     * 首页顶部的"打卡"快捷入口（注意节点本身不可点，需点父级）。
     */
    val QUICK_PUNCH = listOf("打卡")

    /**
     * 考勤入口候选（工作台页里的应用图标）。
     *
     * 顺序：精确名在前。
     */
    val ENTRY_ATTENDANCE = listOf(
        "考勤打卡",
        "智能考勤",
        "考勤",
    )

    // ==================== 打卡按钮 ====================

    /**
     * "上班打卡"按钮候选。
     *
     * 注意：绝不能把裸"打卡"放进来 —— 页面上可能有"打卡记录"、
     * "打卡详情"、"查看详情"等多个含"打卡"的元素。
     */
    val BTN_CLOCK_IN = listOf(
        "上班打卡",
        "上班 打卡",
        "上班",
    )

    /** "下班打卡"按钮候选 */
    val BTN_CLOCK_OUT = listOf(
        "下班打卡",
        "下班 打卡",
        "下班",
    )

    // ==================== 结果判定 ====================

    /**
     * 打卡成功信号 —— 成功判定的唯一依据。
     *
     * 实测钉钉打卡成功后会弹出卡片，主文案是"打卡成功"，
     * 并附带"查看详情"。**"查看详情"本身不是成功信号**，
     * 它只说明弹出了某个结果卡片。
     */
    val SUCCESS_SIGNALS = listOf(
        "打卡成功",
        "考勤成功",
        "打卡完成",
        "更新成功",
    )

    /** 已打卡（今天这个时段不需要再打） */
    val ALREADY_DONE_SIGNALS = listOf(
        "今日已打卡",
        "已完成打卡",
        "已打卡",
    )

    /**
     * 明确的失败信号。
     *
     * 判定顺序上必须先查失败再查成功：如果同时出现"打卡成功"和
     * "不在打卡范围"（部分成功的边缘情况），宁可判失败让用户知情。
     */
    val FAILURE_SIGNALS = listOf(
        "打卡失败",
        "不在打卡范围",
        "请在公司范围内打卡",
        "考勤组未设置",
        "网络异常",
        "打卡异常",
        "定位失败",
        "请开启定位",
    )

    /**
     * 「外勤打卡」信号 —— 检测到就**绝不能点**。
     *
     * 实测（Redmi K90 / 1280x2772 / 钉钉当前版本）打卡页有三种形态：
     *
     * 1. **内勤可打**：大按钮是绿色圆，文字"下班打卡"，下方无提示。
     * 2. **外勤可打**：大按钮顶部多一行"外勤"，变成"外勤 / 下班打卡"，
     *    下方出现"未进入考勤范围，可外勤打卡 / 如需内勤打卡，请检查"。
     * 3. **已打卡**：上方状态卡显示"09:30已打卡"。
     *
     * 第 2 种状态下点了会生成一条**外勤打卡记录**：
     * - 位置被记为"外勤"，很多公司需要额外审批才认；
     * - 有些公司直接不认外勤，等于白打还可能被标记异常；
     * - 而且它是"已打卡"状态，之后想补内勤就得走补卡流程。
     *
     * 所以用户明确要求：**发现外勤就先不打，等到能正常打卡为止**。
     */
    val OUTDOOR_SIGNALS = listOf(
        "未进入考勤范围",
        "可外勤打卡",
        "如需内勤打卡",
        "外勤打卡",
    )

    /** 判断当前页面是否是"外勤可打"状态 */
    fun isOutdoor(blob: String): Boolean {
        if (blob.isEmpty()) return false
        // "外勤" 单独出现在按钮上也算（大按钮第一行就是"外勤"）
        return OUTDOOR_SIGNALS.any { blob.contains(it) }
    }

    /** 常见弹窗关闭按钮 */
    val POPUP_DISMISS = listOf(
        "我知道了",
        "知道了",
        "关闭",
        "以后再说",
        "暂不",
        "跳过",
    )

    /**
     * 触发"点了但没跳转"误判的元素。
     *
     * 这些文本出现过就说明我们在错的地方（比如消息列表、汇报页）。
     * 用于导航校验：如果点完之后界面上出现了这些词，说明点错了。
     */
    val WRONG_PAGE_MARKERS = listOf(
        "汇报工作",
        "日志",
        "审批",
        "请假",
    )

    /** 钉钉关键 resourceId 前缀（辅助定位） */
    const val ID_PREFIX = "com.alibaba.android.rimet:id/"

    // ==================== 判定函数 ====================

    /** 是否命中成功信号 */
    fun containsSuccess(text: String): String? =
        SUCCESS_SIGNALS.firstOrNull { text.contains(it) }

    /** 是否命中"已打卡" */
    fun containsAlreadyDone(text: String): String? =
        ALREADY_DONE_SIGNALS.firstOrNull { text.contains(it) }

    /** 是否命中失败信号 */
    fun containsFailure(text: String): String? =
        FAILURE_SIGNALS.firstOrNull { text.contains(it) }

    /** 是否在错误页面（导航校验用） */
    fun looksLikeWrongPage(text: String): Boolean =
        WRONG_PAGE_MARKERS.any { text.contains(it) }
}